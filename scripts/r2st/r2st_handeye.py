#!/usr/bin/env python3
"""Eye-to-hand calibration for a STATIC camera watching the Panda, using a ChArUco board
that is fixed to the table (not to the gripper).

    This rig's board: 8x11 squares, 15 mm checkers, 11 mm markers, a DICT_4X4 dictionary
    -> 70 inner corners spanning 90 x 135 mm. ChArUco beats a plain checkerboard here
    because every corner carries a unique id, so "I touched corner 47" is unambiguous even
    when the arm hides part of the board.

WHY THIS EXISTS
    real2sim-toolkit's `examples/estimate_camera_extrinsics.py` uses the robot itself as
    the calibration target: it renders Jrl2's panda at the demo joint angles, masks the
    real robot with SAM 3, and fits T_base_cam by minimising a ONE-SIDED chamfer distance
    from the real cloud to the sim cloud. On this rig it does not converge to the true
    pose (measured 2026-09-06):

      * Seeded with a pose whose table normal is exactly [0,0,1] (cost 0.0266), CMA-ES
        LOWERED the cost to 0.0145 while tilting the table to 5.9 deg. The optimum of the
        objective is not the true pose, so no amount of re-seeding fixes it.
      * Two runs on one calibration clip agreed to 1.2 cm / 3.3 deg yet both placed the
        table 0.65 m above the robot base at ~45 deg tilt.
      * Two task demos with healthy masks throughout disagreed by 0.53 m / 157 deg.

    Contributing causes: the one-sided chamfer charges for real points with no sim
    counterpart, the SAM 3 masks include cables and sometimes drop the whole gripper, and
    the real arm carries a wrist-camera mount that Jrl2's `panda` does not model.

    A checkerboard sidesteps all of it: the board's geometry is known exactly, so the
    camera's pose relative to it comes from PnP, and the only thing the robot has to do
    is tell us where the board sits in its own base frame.

THE MATH
    T_base_cam = T_base_board @ inv(T_cam_board)

    `T_cam_board` comes from `detect`: cv2.aruco.CharucoDetector + solvePnP against the
    D435's factory colour intrinsics (verified to match r2st.constants COLOR_INTRINSICS).

    `T_base_board` comes from `touch`: put the arm in guiding mode, physically touch N>=3
    named board corners with the closed fingertips, and record qpos at each. Jrl2 FK gives
    `panda_hand_tcp` in the base frame; the board's own grid gives the same points in
    board coordinates; Umeyama (rigid, no scale) fits the transform between them.

    Touching by hand in guiding mode beats jogging with the SpaceMouse: you can feel the
    contact, and there is no controller settling error.

USAGE
    # 1. board pose in the camera, from the live D435 topic (camera must NOT move after this)
    source /opt/ros/humble/setup.bash && source ~/anaconda3/bin/activate deoxys
    python scripts/r2st/r2st_handeye.py detect --out ~/Desktop/data/handeye

    # 2. touch corners.  Franka in guiding mode; Enter records, 'q' finishes.
    python scripts/r2st/r2st_handeye.py touch --out ~/Desktop/data/handeye

    # 3. solve (needs Jrl2 -> r2st env)
    source ~/anaconda3/bin/activate r2st
    python scripts/r2st/r2st_handeye.py solve --out ~/Desktop/data/handeye \
        --extrinsics-out ~/Desktop/data/r2st/square_smoke/extrinsics_cam_1.yaml

    The YAML `solve` writes is exactly the schema track_object.py's --extrinsics-path
    reads (it asserts on `camera`, `camera_model_id` and a 4x4 `matrix`), so nothing
    downstream needs to change.

CORNER NAMING
    Corner ids are ChArUco ids straight from OpenCV -- the same numbering
    `board.getChessboardCorners()` uses, so there is no bookkeeping to get wrong.
    `detect` writes an annotated PNG with every detected id drawn on it. Touch ids you can
    actually see in that PNG, and spread them out: the four extreme corners plus the
    centre is a good set, and a wide baseline is what keeps the rotation accurate.

    If the board was generated by OpenCV < 4.7 its marker layout differs; pass
    --legacy-pattern if ids are detected but the pose looks wrong.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

COLOR_TOPIC = "/camera/d435/color/image_raw"
INFO_TOPIC = "/camera/d435/color/camera_info"

# Intrinsics are read LIVE from camera_info rather than hardcoded, because the useful
# calibration resolution is not the useful recording resolution: at 640x480 this board's
# 11 mm markers land on ~10 px and cannot be decoded, while 1280x720 doubles that. The
# extrinsics this script solves for is a camera POSE, so it stays valid when the node is
# relaunched at another profile -- as long as the camera itself is not moved.


def make_board(args: argparse.Namespace):
    """The ChArUco board this rig uses, as an OpenCV object."""
    import cv2

    dictionary = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, args.dict))
    board = cv2.aruco.CharucoBoard(
        (args.squares_x, args.squares_y), args.square_mm / 1000.0, args.marker_mm / 1000.0, dictionary
    )
    if args.legacy_pattern:
        board.setLegacyPattern(True)
    return board


def board_object_points(args: argparse.Namespace) -> np.ndarray:
    """Inner-corner positions in the board frame, indexed by ChArUco id."""
    return np.asarray(make_board(args).getChessboardCorners(), dtype=np.float64)


def grab_color_frame(timeout_s: float = 15.0) -> tuple[np.ndarray, np.ndarray]:
    """One RGB frame plus the matching 3x3 K off the live D435 topics.

    The ROS node owns the device, so V4L2 and pyrealsense2 cannot open it concurrently.
    """
    import time

    import rclpy
    from rclpy.node import Node
    from sensor_msgs.msg import CameraInfo, Image

    got: dict[str, np.ndarray] = {}
    rclpy.init()
    node = Node("r2st_handeye_grab")
    node.create_subscription(
        Image,
        COLOR_TOPIC,
        lambda m: got.__setitem__("rgb", np.frombuffer(m.data, np.uint8).reshape(m.height, m.width, 3)),
        10,
    )
    node.create_subscription(
        CameraInfo, INFO_TOPIC, lambda m: got.__setitem__("K", np.asarray(m.k, dtype=np.float64).reshape(3, 3)), 10
    )
    t0 = time.time()
    while time.time() - t0 < timeout_s and len(got) < 2:
        rclpy.spin_once(node, timeout_sec=0.05)
    node.destroy_node()
    rclpy.shutdown()
    assert "rgb" in got, f"no frame on {COLOR_TOPIC} within {timeout_s:.0f}s -- is the D435 node up?"
    assert "K" in got, f"no camera_info on {INFO_TOPIC} within {timeout_s:.0f}s"
    return got["rgb"], got["K"]


def _try_board(gray, args, sx, sy, legacy):
    """Detect with one (squares_x, squares_y, legacy) hypothesis."""
    import cv2

    a = argparse.Namespace(**{**vars(args), "squares_x": sx, "squares_y": sy, "legacy_pattern": legacy})
    board = make_board(a)
    ch_corners, ch_ids, mk_corners, mk_ids = cv2.aruco.CharucoDetector(board).detectBoard(gray)
    n_ch = 0 if ch_ids is None else len(ch_ids)
    n_mk = 0 if mk_ids is None else len(mk_ids)
    return n_ch, n_mk, ch_corners, ch_ids, mk_corners, mk_ids, a


def cmd_detect(args: argparse.Namespace) -> int:
    import cv2

    out = Path(args.out).expanduser()
    out.mkdir(parents=True, exist_ok=True)
    rgb, K = grab_color_frame()
    bgr = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
    gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)
    print(f"frame {rgb.shape[1]}x{rgb.shape[0]}   fx={K[0,0]:.2f} fy={K[1,1]:.2f} cx={K[0,2]:.2f} cy={K[1,2]:.2f}")

    # The board's orientation in the frame and its OpenCV generation are both easy to get
    # wrong and cheap to test, so sweep them instead of making the user guess.
    hypotheses = []
    for sx, sy in {(args.squares_x, args.squares_y), (args.squares_y, args.squares_x)}:
        for legacy in (False, True):
            hypotheses.append((sx, sy, legacy))
    results = [(_try_board(gray, args, sx, sy, lg), (sx, sy, lg)) for sx, sy, lg in hypotheses]
    print("  hypothesis sweep (squares_x x squares_y, legacy) -> ChArUco corners / markers:")
    for (n_ch, n_mk, *_), (sx, sy, lg) in results:
        print(f"    {sx:2d}x{sy:<2d} legacy={str(lg):5s} -> {n_ch:3d} corners, {n_mk:3d} markers")
    (n_ch, n_mk, ch_corners, ch_ids, mk_corners, mk_ids, a), best = max(results, key=lambda r: r[0][0])

    if n_ch < 6:
        cv2.imwrite(str(out / "detect_FAILED.png"), bgr)
        print(f"\nFAILED: best hypothesis gave {n_ch} ChArUco corners, {n_mk} markers (need >= 6).")
        print(f"  wrote {out/'detect_FAILED.png'}")
        print("  Most likely the board is too small in frame: a 4x4 ArUco needs roughly 20+ px")
        print("  per marker to decode. Relaunch the D435 at 1280x720 (it is on USB 3.2 now) and/or")
        print("  move the board closer to the camera, keeping it inside the arm's reach.")
        return 1

    objp_all = np.asarray(make_board(a).getChessboardCorners(), dtype=np.float64)
    ids = ch_ids.ravel()
    objp = objp_all[ids]
    img_pts = ch_corners.reshape(-1, 2)
    ok, rvec, tvec = cv2.solvePnP(objp, img_pts, K, None, flags=cv2.SOLVEPNP_ITERATIVE)
    assert ok, "solvePnP failed despite a successful ChArUco detection"
    proj, _ = cv2.projectPoints(objp, rvec, tvec, K, None)
    reproj_px = float(np.linalg.norm(proj.reshape(-1, 2) - img_pts, axis=1).mean())

    R, _ = cv2.Rodrigues(rvec)
    T_cam_board = np.eye(4)
    T_cam_board[:3, :3] = R
    T_cam_board[:3, 3] = tvec.ravel()

    vis = bgr.copy()
    if mk_ids is not None:
        cv2.aruco.drawDetectedMarkers(vis, mk_corners, mk_ids)
    cv2.aruco.drawDetectedCornersCharuco(vis, ch_corners, ch_ids, (0, 0, 255))
    for i, c in zip(ids, img_pts):
        cv2.putText(vis, str(int(i)), (int(c[0]) + 4, int(c[1]) - 4), cv2.FONT_HERSHEY_SIMPLEX, 0.32, (0, 255, 0), 1)
    cv2.drawFrameAxes(vis, K, None, rvec, tvec, 0.05)
    cv2.imwrite(str(out / "detect.png"), vis)
    np.save(out / "T_cam_board.npy", T_cam_board)
    np.save(out / "K.npy", K)
    (out / "board.json").write_text(json.dumps({
        "squares_x": a.squares_x, "squares_y": a.squares_y, "legacy_pattern": bool(a.legacy_pattern),
        "square_mm": a.square_mm, "marker_mm": a.marker_mm, "dict": a.dict,
        "image_wh": [int(rgb.shape[1]), int(rgb.shape[0])], "K": K.tolist(),
        "n_markers": int(n_mk), "n_corners": int(len(ids)),
        "detected_ids": [int(i) for i in ids], "reproj_px": reproj_px,
    }, indent=2))
    print(f"\nWINNER: squares {a.squares_x}x{a.squares_y}, legacy={a.legacy_pattern}")
    print(f"  {n_mk} markers, {len(ids)} ChArUco corners, mean reprojection {reproj_px:.3f} px")
    print(f"  board is {np.linalg.norm(tvec):.3f} m from the camera")
    print(f"  detected corner ids: {sorted(int(i) for i in ids)}")
    print(f"  wrote {out/'detect.png'} (ids drawn, axes at the board origin), T_cam_board.npy, K.npy")
    if reproj_px > 1.0:
        print("  WARNING: reprojection > 1 px -- re-check --square-mm / --marker-mm and board flatness.")
    return 0


def cmd_touch(args: argparse.Namespace) -> int:
    """Jog to each board corner with the SpaceMouse and record qpos there.

    Hand-guiding (the wrist buttons) is NOT usable on this rig: the Franka is either in
    programming mode, where guiding works but the FCI is down and deoxys sees no joint
    state, or in execution mode, where deoxys holds the FCI and pressing the guiding
    buttons conflicts with the external controller -- the status light goes pink and the
    arm stops. So we keep the FCI and jog with the SpaceMouse instead, exactly as
    log_demonstration.py does.
    """
    import select
    import sys
    import threading
    import time

    from deoxys.franka_interface import FrankaInterface
    from deoxys.utils.config_utils import get_default_controller_config
    from deoxys.utils.input_utils import input2action
    from deoxys.utils.io_devices import SpaceMouse

    controller_type = "OSC_POSE"
    out = Path(args.out).expanduser()
    out.mkdir(parents=True, exist_ok=True)
    rec_path = out / "touches.json"
    touches = json.loads(rec_path.read_text()) if rec_path.is_file() else []
    if touches:
        print(f"resuming: {len(touches)} touches already recorded ({sorted(t['index'] for t in touches)})")

    n_corners = len(board_object_points(args))
    cfg = args.interface_cfg or str(Path(__file__).resolve().parents[1] / "configs" / "charmander.yml")
    robot = FrankaInterface(cfg, use_visualizer=False)
    t0 = time.time()
    while time.time() - t0 < 10 and robot.last_q is None:
        time.sleep(0.05)
    assert robot.last_q is not None, "no joint state from deoxys -- are the NUC binaries running?"

    device = SpaceMouse(vendor_id=args.vendor_id, product_id=args.product_id)
    device.start_control()

    running = True

    def teleop() -> None:
        controller_cfg = get_default_controller_config(controller_type=controller_type)
        period = 1.0 / 50.0
        while running:
            time.sleep(period)
            try:
                action, _ = input2action(device=device, controller_type=controller_type)
                robot.control(controller_type=controller_type, action=action, controller_cfg=controller_cfg)
            except Exception as exc:  # noqa: BLE001 -- keep the prompt alive
                print(f"  teleop error: {exc}")
                break

    th = threading.Thread(target=teleop, daemon=True)
    th.start()

    print()
    print("SpaceMouse teleop is live. Jog the CLOSED fingertips onto a board corner, then")
    print("type that corner's id and press Enter. 'q' finishes. Re-typing an id overwrites it.")
    print(f"Valid ids: 0 .. {n_corners - 1}   (see detect.png)")
    print("Approach every corner the same way -- a constant fingertip offset cancels out,")
    print("a varying one does not.")
    print()
    try:
        while True:
            sys.stdout.write("corner id (or q): ")
            sys.stdout.flush()
            line = None
            while line is None:
                if select.select([sys.stdin], [], [], 0.1)[0]:
                    line = sys.stdin.readline()
            sline = line.strip()
            if sline.lower() in ("q", "quit"):
                break
            if not sline.isdigit() or not (0 <= int(sline) < n_corners):
                print(f"  need an integer in 0..{n_corners - 1}")
                continue
            q = robot.last_q
            if q is None:
                print("  no joint state right now, try again")
                continue
            rec = {
                "index": int(sline),
                "q": [float(v) for v in np.asarray(q).ravel()],
                "gripper_q": None if robot.last_gripper_q is None else float(robot.last_gripper_q),
            }
            touches = [t for t in touches if t["index"] != rec["index"]] + [rec]
            rec_path.write_text(json.dumps(touches, indent=2))
            print(f"  recorded corner {sline}  ({len(touches)} total: {sorted(t['index'] for t in touches)})")
    finally:
        running = False
        th.join(timeout=1.0)
        robot.close()
    print(f"\nwrote {rec_path} with {len(touches)} touches")
    if len(touches) < 3:
        print("  NOTE: need at least 3 (4-5 well spread is much better) before `solve`.")
    return 0


def umeyama_rigid(src: np.ndarray, dst: np.ndarray) -> np.ndarray:
    """Least-squares rigid transform taking `src` onto `dst` (no scaling)."""
    assert src.shape == dst.shape and src.shape[0] >= 3, f"need >=3 matched points, got {src.shape}"
    cs, cd = src.mean(0), dst.mean(0)
    H = (src - cs).T @ (dst - cd)
    U, _, Vt = np.linalg.svd(H)
    d = np.sign(np.linalg.det(Vt.T @ U.T))
    R = Vt.T @ np.diag([1.0, 1.0, d]) @ U.T
    T = np.eye(4)
    T[:3, :3] = R
    T[:3, 3] = cd - R @ cs
    return T


def cmd_solve(args: argparse.Namespace) -> int:
    import warnings

    warnings.filterwarnings("ignore")
    from jrl2.robots import ALL_ROBOTS

    out = Path(args.out).expanduser()
    T_cam_board = np.load(out / "T_cam_board.npy")
    touches = json.loads((out / "touches.json").read_text())
    assert len(touches) >= 3, f"need >=3 touches, found {len(touches)}"

    robot = [c() for c in ALL_ROBOTS if c().name == "panda"][0]
    names = list(robot.actuated_joint_names)

    meta = json.loads((out / "board.json").read_text())
    a = argparse.Namespace(**{**vars(args), "squares_x": meta["squares_x"], "squares_y": meta["squares_y"],
                              "legacy_pattern": meta["legacy_pattern"], "square_mm": meta["square_mm"],
                              "marker_mm": meta["marker_mm"], "dict": meta["dict"]})
    objp = board_object_points(a)
    print(f"board geometry from detect: {a.squares_x}x{a.squares_y} squares, legacy={a.legacy_pattern}")
    p_board, p_base = [], []
    for t in touches:
        q = list(t["q"])
        # the logger records 7 arm joints; Jrl2's panda actuates 9 (7 + two fingers)
        while len(q) < len(names):
            q.append(0.0)
        poses = robot.get_all_link_poses_non_batched({n: float(v) for n, v in zip(names, q)})
        p_base.append(np.asarray(poses[args.tcp_link])[:3, 3])
        p_board.append(objp[t["index"]])
    p_board = np.asarray(p_board)
    p_base = np.asarray(p_base)

    # The fingertip contact point sits `--tip-offset-m` below panda_hand_tcp along the
    # gripper's own approach axis; ignoring it shifts the board plane without rotating it.
    if args.tip_offset_m:
        for i, t in enumerate(touches):
            q = list(t["q"])
            while len(q) < len(names):
                q.append(0.0)
            poses = robot.get_all_link_poses_non_batched({n: float(v) for n, v in zip(names, q)})
            R_tcp = np.asarray(poses[args.tcp_link])[:3, :3]
            p_base[i] = p_base[i] + R_tcp[:, 2] * args.tip_offset_m

    T_base_board = umeyama_rigid(p_board, p_base)
    resid = np.linalg.norm((T_base_board[:3, :3] @ p_board.T).T + T_base_board[:3, 3] - p_base, axis=1)
    T_base_cam = T_base_board @ np.linalg.inv(T_cam_board)

    print(f"solved from {len(touches)} touches: indices {[t['index'] for t in touches]}")
    print(f"  per-point residual (mm): {np.round(resid * 1000, 2).tolist()}")
    print(f"  RMS {np.sqrt((resid ** 2).mean()) * 1000:.2f} mm   max {resid.max() * 1000:.2f} mm")
    n_board = T_base_board[:3, :3] @ np.array([0.0, 0.0, 1.0])
    print(f"  board normal in base frame: [{n_board[0]:+.4f} {n_board[1]:+.4f} {n_board[2]:+.4f}]"
          f"  -> {np.degrees(np.arccos(abs(n_board[2]))):.2f} deg from vertical")
    print(f"  board z in base frame     : {T_base_board[2, 3]:+.4f} m")
    print()
    print(f"  T_base_cam translation: [{T_base_cam[0,3]:+.4f} {T_base_cam[1,3]:+.4f} {T_base_cam[2,3]:+.4f}]")

    if args.extrinsics_out:
        import yaml

        path = Path(args.extrinsics_out).expanduser()
        path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "camera": args.camera,
            "camera_model_id": args.camera_model_id,
            "robot_id": "panda",
            "depth_intrinsics_source": "rgb",
            "parent_frame": "robot_base",
            "child_frame": f"{args.camera}_optical",
            "source": "r2st_handeye.py (checkerboard on table + FK touch points)",
            "n_touches": len(touches),
            "touch_rms_m": float(np.sqrt((resid ** 2).mean())),
            "matrix": [[float(v) for v in row] for row in T_base_cam],
        }
        path.write_text(yaml.safe_dump(payload, sort_keys=False))
        print(f"\nwrote {path}")
    return 0


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    def common(sp):
        sp.add_argument("--out", required=True, help="working directory for this calibration")
        # defaults describe THIS rig's board; every value must match the printed article
        sp.add_argument("--squares-x", type=int, default=8, help="board width in SQUARES (default 8)")
        sp.add_argument("--squares-y", type=int, default=11, help="board height in SQUARES (default 11)")
        sp.add_argument("--square-mm", type=float, default=20.0, help="checker square side, mm (default 20 -- MEASURED via robot touch points; the printed spec said 15 but the pairwise distances say 20.05)")
        sp.add_argument("--marker-mm", type=float, default=15.0, help="ArUco marker side, mm (default 15)")
        sp.add_argument("--dict", default="DICT_4X4_50", help="cv2.aruco dictionary name (default DICT_4X4_50)")
        sp.add_argument("--legacy-pattern", action="store_true",
                        help="board generated by OpenCV < 4.7 (different marker layout)")

    d = sub.add_parser("detect", help="detect the board in the live D435 frame -> T_cam_board")
    common(d)
    d.set_defaults(func=cmd_detect)

    t = sub.add_parser("touch", help="record qpos while touching named board corners")
    common(t)
    t.add_argument("--interface-cfg", default=None)
    t.add_argument("--vendor-id", type=int, default=1133, help="SpaceMouse vendor id (0x046D)")
    t.add_argument("--product-id", type=int, default=50726, help="SpaceMouse product id (0xC626)")
    t.set_defaults(func=cmd_touch)

    s = sub.add_parser("solve", help="combine both into T_base_cam and write the extrinsics YAML")
    common(s)
    s.add_argument("--tcp-link", default="panda_hand_tcp")
    s.add_argument("--tip-offset-m", type=float, default=0.0,
                   help="distance from panda_hand_tcp to the actual contact point, along the "
                        "gripper approach axis (+z). Leave 0 unless the residuals say otherwise.")
    s.add_argument("--camera", default="cam_1")
    s.add_argument("--camera-model-id", default="d435")
    s.add_argument("--extrinsics-out", default=None, help="write the toolkit-schema YAML here")
    s.set_defaults(func=cmd_solve)

    args = p.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
